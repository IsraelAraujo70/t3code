import { describe, expect, it } from "vite-plus/test";
import { citesHeavyScript, classifyCommand } from "./command.ts";

describe("classifyCommand", () => {
  it.each([
    ["git -C . push", "protected", "merge"],
    ["git -c core.x=1 push origin wf/x", "allowed"],
    ["git status", "allowed"],
    ["git push origin wf/merge-v1", "allowed"],
    ["git push origin HEAD:refs/heads/wf/x", "allowed"],
    ["git push", "protected", "merge"],
    ["git push origin friend/main", "protected", "merge"],
    ["git push origin HEAD:friend/main", "protected", "merge"],
    ["git push -f origin wf/x", "protected", "force-push"],
    ["git push origin +wf/x", "protected", "force-push"],
    ["git push --force-with-lease origin friend/main", "protected", "force-push"],
    ["gh pr merge 12 --squash", "protected", "merge"],
    ["gh pr create --draft", "protected", "deploy"],
    ["systemctl --user restart t3-friend", "protected", "restart"],
    ["railway up", "protected", "deploy"],
    ["cp x /home/israel/.t3/userdata/settings.json", "protected", "settings"],
    ["sudo ls", "forbidden"],
    ["crontab -l", "forbidden"],
    ["bash -c x", "inline-shell"],
    ["vp test run x", "allowed"],
    ["gh pr merge 1", "protected", "merge"],
    ["gh pr view 1", "allowed"],
    ["env FOO=1 systemctl --user restart t3", "protected", "restart"],
    ["timeout -s KILL 10 pkill node", "protected", "restart"],
    ["bash -lc echo", "inline-shell"],
    ["bash scripts/x.sh", "allowed"],
    ["bash", "inline-shell"],
    ["node -e 1", "inline-shell"],
    ["node scripts/friend/check-seams.ts", "allowed"],
    ["python3.12 -c x", "inline-shell"],
    ["node scripts/friend/deploy-prod.ts", "protected", "deploy"],
    ["vp run release", "protected", "deploy"],
    ["pnpm publish", "protected", "deploy"],
    ["rm -rf /", "forbidden"],
    ["rm -rf build", "allowed"],
    ["{{params.tool}} x", "forbidden"],
    ["xargs rm", "forbidden"],
    ["/usr/bin/sudo ls", "forbidden"],
    ["vp i", "allowed"],
    ["cargo build --release --locked", "allowed"],
    ["nice -n 5 nohup sudo ls", "forbidden"],
    ["stdbuf -o L systemctl status", "protected", "restart"],
    ["time ssh host", "protected", "deploy"],
    ["deno eval x", "inline-shell"],
    ["ruby -E x", "inline-shell"],
    ["update-mac-app.sh", "protected", "deploy"],
    ["rm --recursive --force ~/", "forbidden"],
    ["npm restart", "protected", "restart"],
    ["yarn deploy", "protected", "deploy"],
    ["pnpm run stop", "protected", "restart"],
    ["fish --command x", "inline-shell"],
    ["node -econsole.log(1)", "inline-shell"],
    ["node -pe 1", "inline-shell"],
    ["python3 -cprint(1)", "inline-shell"],
    ["perl -ne x", "inline-shell"],
    ["node scripts/x.ts -e flag", "allowed"],
    ["bash scripts/x.sh -c flag", "allowed"],
    ["env -S x", "forbidden"],
    ["git push --force origin wf/x", "protected", "force-push"],
    ["systemctl restart t3-friend", "protected", "restart"],
    ["npm run deploy", "protected", "deploy"],
    ["vp run restart", "protected", "restart"],
    ["yarn run restart", "protected", "restart"],
    ["tee /home/israel/.t3/userdata/settings.json", "protected", "settings"],
    ["vp test run release-notes.test.ts", "allowed"],
    ["pnpm add release-it", "allowed"],
    ["cat /home/israel/.t3/userdata/settings.json", "allowed"],
    ["jq . /home/israel/.t3/userdata/settings.json", "allowed"],
    ["cp /home/israel/.t3/userdata/settings.json /tmp/x", "allowed"],
    [
      "cp /home/israel/.t3/userdata/settings.json /home/israel/.t3/userdata/settings.json.bak",
      "allowed",
    ],
    ["cp x ~/.t3/userdata/settings.json", "protected", "settings"],
    ["mv /home/israel/.t3/userdata/settings.json /tmp/x", "protected", "settings"],
    ["node scripts/x.ts /home/israel/.t3/userdata/settings.json", "protected", "settings"],
  ])("%s is %s", (command, kind, action?: string) => {
    const result = classifyCommand(command.split(" "));
    expect(result.kind).toBe(kind);
    if (result.kind === "protected") expect(result.action).toBe(action);
  });
});

describe("citesHeavyScript", () => {
  it.each([
    [["/home/israel/.cache/t3-testdata/heavy.sh", "vp", "test"], true],
    [["vp", "test"], false],
    [["heavy.sh.bak"], false],
  ])("recognizes %j", (argv, expected) => expect(citesHeavyScript(argv)).toBe(expected));
});
